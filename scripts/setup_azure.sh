#!/usr/bin/env bash
# SciNova OS — Azure VM setup after you have cloned the repo.
#
# Target: rapid-build-dev-server (Ubuntu 24.04, Standard_D2s_v3, East US).
# On the VM:
#
#   git clone https://github.com/saurabhdsh/scinova-os.git
#   cd scinova-os
#   bash scripts/setup_azure.sh
#
# The script installs Docker, writes an OpenAI .env for this VM, and starts
# docker compose in the clone you are standing in.
#
# Optional:
#   PUBLIC_HOST=20.127.186.132   # used in CORS; Azure metadata wins when present
#   SKIP_COMPOSE=1

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_URL="${REPO_URL:-${SCINOVA_REPO_URL:-https://github.com/saurabhdsh/scinova-os.git}}"
BRANCH="${BRANCH:-${SCINOVA_BRANCH:-main}}"
INSTALL_DIR="${INSTALL_DIR:-${SCINOVA_DIR:-$REPO_ROOT}}"
PUBLIC_HOST="${PUBLIC_HOST:-}"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

info()  { echo -e "${GREEN}==>${NC} $*"; }
warn()  { echo -e "${YELLOW}WARN${NC} $*"; }
fail()  { echo -e "${RED}FAIL${NC} $*"; exit 1; }

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || return 1
}

azure_public_ip() {
  local ip
  ip="$(curl -sf -H "Metadata:true" --connect-timeout 2 \
    "http://169.254.169.254/metadata/instance/network/interface/0/ipv4/ipAddress/0/publicIpAddress?api-version=2021-02-01&format=text" \
    2>/dev/null | tr -d '[:space:]' || true)"
  if [[ -n "$ip" && "$ip" != "null" ]]; then
    echo "$ip"
  fi
}

ensure_compose_plugin() {
  if docker compose version >/dev/null 2>&1 || sudo docker compose version >/dev/null 2>&1; then
    return 0
  fi
  info "Installing Docker Compose plugin…"
  sudo mkdir -p /usr/local/lib/docker/cli-plugins
  sudo curl -fsSL \
    "https://github.com/docker/compose/releases/download/v2.29.7/docker-compose-linux-x86_64" \
    -o /usr/local/lib/docker/cli-plugins/docker-compose
  sudo chmod +x /usr/local/lib/docker/cli-plugins/docker-compose
}

if [[ -z "$PUBLIC_HOST" ]]; then
  PUBLIC_HOST="$(azure_public_ip || true)"
fi
PUBLIC_HOST="${PUBLIC_HOST:-20.127.186.132}"

info "Installing base packages (git, curl, jq)…"
if need_cmd apt-get; then
  sudo apt-get update -y
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y ca-certificates curl git unzip jq
else
  warn "This VM is expected to be Ubuntu. Install git, curl, and docker yourself if apt-get is missing."
fi

if ! need_cmd docker; then
  info "Installing Docker Engine…"
  curl -fsSL https://get.docker.com | sudo sh
  sudo systemctl enable --now docker || true
fi

ensure_compose_plugin

if ! docker compose version >/dev/null 2>&1 && ! sudo docker compose version >/dev/null 2>&1; then
  fail "docker compose plugin missing after install."
fi

if ! groups | grep -q '\bdocker\b'; then
  info "Adding $USER to docker group…"
  sudo usermod -aG docker "$USER" || true
  warn "You may need to log out/in (or run: newgrp docker) if docker commands fail with permission denied."
fi

DOCKER=(docker)
if ! docker info >/dev/null 2>&1; then
  DOCKER=(sudo docker)
fi

info "Docker: $(${DOCKER[@]} --version)"
info "Compose: $(${DOCKER[@]} compose version)"
info "Public host: $PUBLIC_HOST"

clone_url="$REPO_URL"
if [[ -n "${GITHUB_TOKEN:-}" ]]; then
  clone_url="$(echo "$REPO_URL" | sed -E "s#https://#https://${GITHUB_TOKEN}@#")"
fi

if [[ -d "$INSTALL_DIR/.git" ]]; then
  info "Using the clone at $INSTALL_DIR"
  git -C "$INSTALL_DIR" pull --ff-only origin "$BRANCH" || \
    warn "Could not fast-forward. Continuing with the commit already checked out."
else
  info "Cloning $REPO_URL → $INSTALL_DIR (branch $BRANCH)…"
  rm -rf "$INSTALL_DIR"
  git clone --branch "$BRANCH" --single-branch "$clone_url" "$INSTALL_DIR"
fi

cd "$INSTALL_DIR"
info "Commit: $(git log -1 --oneline)"

ENV_FILE="$INSTALL_DIR/.env"
if [[ -f "$ENV_FILE" ]]; then
  warn ".env already exists — leaving secrets in place."
  if ! grep -q '^SCINOVA_CLOUD=' "$ENV_FILE"; then
    echo "SCINOVA_CLOUD=azure" >> "$ENV_FILE"
  fi
  if ! grep -q "$PUBLIC_HOST" "$ENV_FILE"; then
    warn "Add this origin to CORS if the browser cannot reach the API:"
    warn "  CORS_ORIGINS=http://${PUBLIC_HOST}:5173,http://localhost:5173"
  fi
else
  info "Writing OpenAI-oriented .env (no AWS keys; this VM has no Bedrock role)…"
  SECRET_KEY="$(openssl rand -hex 32 2>/dev/null || head -c 32 /dev/urandom | xxd -p)"
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup_azure.sh — do not commit
# rapid-build-dev-server uses OpenAI. EC2 uses Bedrock via its IAM role.
SCINOVA_CLOUD=azure
DEFAULT_LLM_PROVIDER=openai
BEDROCK_ENABLED=false
ENABLED_LLM_PROVIDERS=openai
LLM_MODEL=gpt-4o-mini
EMBEDDING_PROVIDER=openai
EMBEDDING_MODEL=text-embedding-3-small
OPENAI_API_KEY=
OPENAI_BASE_URL=https://api.openai.com/v1
MISTRAL_API_KEY=
MISTRAL_BASE_URL=https://api.mistral.ai/v1
SLM_MODEL=ministral-8b-latest

SECRET_KEY=${SECRET_KEY}
DEBUG=false
LOG_LEVEL=INFO
ENVIRONMENT=production

CORS_ORIGINS=http://${PUBLIC_HOST}:5173,http://localhost:5173
VITE_ALLOW_ALL_HOSTS=true
EOF
  chmod 600 "$ENV_FILE" || true
  warn "Edit $ENV_FILE and set OPENAI_API_KEY before agents will answer."
fi

if [[ "${SKIP_COMPOSE:-0}" == "1" ]]; then
  warn "SKIP_COMPOSE=1 — not starting containers."
else
  info "Building and starting docker compose stack…"
  ${DOCKER[@]} compose -f "$INSTALL_DIR/docker-compose.yml" up -d --build
  ${DOCKER[@]} compose -f "$INSTALL_DIR/docker-compose.yml" ps
fi

cat <<EOF

${GREEN}SciNova OS Azure setup finished.${NC}

  VM:        rapid-build-dev-server  (Standard_D2s_v3, East US)
  Repo:      $INSTALL_DIR
  Frontend:  http://${PUBLIC_HOST}:5173
  Backend:   http://${PUBLIC_HOST}:8000
  API docs:  http://${PUBLIC_HOST}:8000/docs

Useful:
  cd $INSTALL_DIR
  nano .env                         # OPENAI_API_KEY, and MISTRAL_API_KEY if you use the SLM
  docker compose restart backend celery-worker frontend
  docker compose logs -f backend
  ./scripts/preflight-azure.sh

NSG on NIC rapid-build-dev-server999_z1 must allow TCP 22, 80, 443, 5173, and 8000.
HTTPS for scinova.solutions is the Caddy service: docker compose up -d caddy
Do not open Postgres, Neo4j, Redis, or Chroma.

Standard_D2s_v3 has 8 GiB RAM, same class as the EC2 t3.large. If Neo4j is killed,
resize to Standard_D4s_v3.

EOF
