"""Constrained analogue design for one stored candidate.

Solubility is not measured here. A lower calculated logP is a prediction,
and the parent structure stays in the session.
"""

from __future__ import annotations

from typing import Any

from app.services.chem.research_session import identify_structure, resolve_molecule
from app.services.chemoinformatics_service import compute_molecule_properties


def _props(smiles: str) -> dict[str, Any]:
    props = compute_molecule_properties(smiles)
    return {
        "smiles": props.get("smiles") or smiles,
        "valid": bool(props.get("valid")),
        "logp": props.get("logp"),
        "tpsa": props.get("tpsa"),
        "mw": props.get("molecular_weight"),
        "qed": props.get("qed"),
        "evidence": "calculated",
    }


def optimize_solubility(session: dict[str, Any], query: str, *, selected_molecule_id: str | None = None) -> dict[str, Any]:
    parent = resolve_molecule(session, query, selected_molecule_id)
    if not parent or not parent.get("smiles"):
        return {
            "capability": "PRECONDITION",
            "capability_name": "Scientific prerequisite",
            "summary": "That candidate is not stored.",
            "narrative": "The requested molecule is not in the generated set, so it was not modified.",
            "tools_used": ["Session"],
            "provenance": {"kind": "precondition", "status": "not_run", "evidence": "not_run"},
        }
    before = _props(parent["smiles"])
    if not before["valid"]:
        return {
            "capability": "OPT",
            "capability_name": "Lead optimization",
            "summary": "The stored structure is not a valid molecule.",
            "narrative": (
                f"{parent.get('candidate_id')} did not pass structure validation, "
                "so no analogue was generated."
            ),
            "tools_used": ["RDKit"],
            "provenance": {"kind": "validation", "status": "failed", "evidence": "calculated", "tool": "RDKit"},
        }

    children = _hydroxylate(parent["smiles"])
    scored = []
    for smiles in children:
        props = _props(smiles)
        if not props["valid"]:
            continue
        if props["smiles"] == before["smiles"]:
            continue
        scored.append(props)
    scored.sort(key=lambda row: (row["logp"] if isinstance(row["logp"], (int, float)) else 99))

    parent_id = parent.get("candidate_id")
    if not scored or not isinstance(before.get("logp"), (int, float)) or scored[0]["logp"] >= before["logp"]:
        return {
            "capability": "OPT",
            "capability_name": "Lead optimization",
            "summary": f"No lower-logP analogue was produced for {parent_id}.",
            "narrative": (
                f"{parent_id} was kept unchanged. The supported aromatic hydroxylation "
                "did not yield a valid analogue with a lower calculated logP. "
                "Calculated logP is not a measured solubility."
            ),
            "parent": parent,
            "analogues": [],
            "baseline": before,
            "tools_used": ["RDKit"],
            "provenance": {
                "kind": "prediction",
                "status": "completed",
                "evidence": "calculated",
                "tool": "RDKit",
                "transform": "aromatic hydroxylation",
            },
            "parameters": {"parent_id": parent_id, "objective": "solubility_proxy_logp"},
        }

    best = scored[0]
    identity = identify_structure(best["smiles"])
    child_id = f"{parent_id}-OH"
    child = {
        "candidate_id": child_id,
        "smiles": identity.get("isomeric_smiles") or best["smiles"],
        "canonical_smiles": identity.get("canonical_smiles"),
        "isomeric_smiles": identity.get("isomeric_smiles"),
        "inchi": identity.get("inchi"),
        "inchikey": identity.get("inchikey"),
        "origin": "lead_optimization",
        "state": "generated",
        "evidence": "predicted",
        "clogp": best["logp"],
        "tpsa": best["tpsa"],
        "mw": best["mw"],
        "qed": best["qed"],
        "parent_id": parent_id,
        "lineage": [{
            "parent_id": parent_id,
            "transform": "aromatic hydroxylation",
            "objective": "lower calculated logP as a solubility proxy",
        }],
    }
    narrative = (
        f"Candidate {parent_id} was kept. One analogue, {child_id}, was generated by aromatic hydroxylation. "
        f"Calculated logP moved from {before['logp']:.2f} to {best['logp']:.2f}, "
        f"and calculated TPSA from {before['tpsa']} to {best['tpsa']}. "
        "These are RDKit descriptors, not measured solubility or potency. "
        "The parent structure was not replaced."
    )
    return {
        "capability": "OPT",
        "capability_name": "Lead optimization",
        "summary": f"Proposed a hydroxylated analogue of {parent_id}. Calculated logP {before['logp']:.2f} → {best['logp']:.2f}.",
        "narrative": narrative,
        "parent": {
            "candidate_id": parent_id,
            "smiles": parent.get("smiles"),
            "properties": before,
        },
        "analogues": [child],
        "candidates": [child],
        "baseline": before,
        "tools_used": ["RDKit"],
        "provenance": {
            "kind": "prediction",
            "status": "completed",
            "evidence": "predicted",
            "tool": "RDKit",
            "transform": "aromatic hydroxylation",
            "parent_id": parent_id,
        },
        "parameters": {"parent_id": parent_id, "objective": "solubility_proxy_logp"},
    }


def _hydroxylate(smiles: str) -> list[str]:
    try:
        from rdkit import Chem
        from rdkit.Chem import AllChem
    except ImportError:
        return []
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return []
    try:
        reaction = AllChem.ReactionFromSmarts("[cH:1]>>[c:1]O")
    except Exception:
        return []
    found: list[str] = []
    seen: set[str] = set()
    try:
        products = reaction.RunReactants((mol,))
    except Exception:
        return []
    for group in products[:8]:
        product = group[0]
        try:
            Chem.SanitizeMol(product)
            as_smiles = Chem.MolToSmiles(product)
        except Exception:
            continue
        if as_smiles and as_smiles not in seen:
            seen.add(as_smiles)
            found.append(as_smiles)
        if len(found) >= 4:
            break
    return found
