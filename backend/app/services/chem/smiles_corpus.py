def get_training_smiles() -> list[str]:
    """Deduplicated SMILES list for training (curated seeds + expanded drug-like file)."""
    from pathlib import Path

    seen: set[str] = set()
    out: list[str] = []

    def _add(s: str) -> None:
        s = (s or "").strip()
        if not s or s in seen:
            return
        seen.add(s)
        out.append(s)

    for s in TRAINING_SMILES:
        _add(s)

    expanded = Path(__file__).resolve().parent / "data" / "druglike_smiles.txt"
    if expanded.is_file():
        for line in expanded.read_text(encoding="utf-8").splitlines():
            _add(line)

    return out
